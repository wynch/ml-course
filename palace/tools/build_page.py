#!/usr/bin/env python3
"""Write the palace's data into ../index.html, between the BEGIN DATA and END DATA markers.

The block holds source/palace.json (with each locus's checked card) and the text of
every move the palace shows, read from the One Hundred Moves
page (course/moves/index.html): titles and bodies from its OLD table and its JSON
block, deeper layers from the JSON block. Nothing is fetched at run time.

    python3 course/palace/tools/build_page.py           # write the block
    python3 course/palace/tools/build_page.py --check   # write nothing; exit 1 if the page is stale

It also writes ../formations.js: the formations of the Moves page, cut from its script
between "'use strict';" and "/* ---------- the moves ---------- */", with the fact fixes
of tools/formation_fixes.json applied (each must match exactly once, so a fix the Moves
page has since made itself fails loudly), and the bar-chart specs the palace reuses.
The fix list is empty since the phase 2 review: its 21 fixes were verified against the
modules and made on the Moves page itself. Fix a formation there first; use the list only
for a fact the Moves page cannot carry.
--check fails when formations.js has drifted from what the Moves page gives.
"""
import json, re, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
PAGE = ROOT / "index.html"
MOVES = ROOT.parent / "moves" / "index.html"
BEGIN = "<!-- BEGIN DATA: written by palace/tools/build_page.py; do not edit -->"
END = "<!-- END DATA -->"

JS_STR = r"'((?:[^'\\]|\\.)*)'"


def js_unescape(s):
    return re.sub(r"\\(.)", lambda m: {"n": "\n", "t": "\t"}.get(m.group(1), m.group(1)), s)


def moves_text():
    """Every move's title, body and deeper layer, as the Moves page shows them."""
    html = MOVES.read_text()
    m = re.search(r'<script type="application/json" id="moves-text">(.*?)</script>', html, re.S)
    if not m:
        sys.exit(f"moves-text block not found in {MOVES}")
    block = json.loads(m.group(1))
    script = html[m.end():]
    old = script[script.index("const OLD=["):]
    old = old[:old.index("\n];")]
    rows = re.findall(r"^\[F\.\w+\((?:[^()]|\([^()]*\))*\)," + JS_STR + "," + JS_STR + r"\],?$", old, re.M)
    if len(rows) != 100:
        sys.exit(f"expected 100 OLD rows in {MOVES}, found {len(rows)}")
    out = {}
    for k, (title, body) in enumerate(rows, 1):
        out[f"a{k}"] = {"title": js_unescape(title), "body": js_unescape(body)}
    for mid, t in block["moves"].items():
        e = out.setdefault(mid, {})
        for key in ("title", "body", "deeper"):
            if key in t:
                e[key] = t[key]
    return out


FORM = ROOT / "formations.js"
FIXES = HERE / "formation_fixes.json"
SPECS = ["GROK", "CLIP", "LOSSB", "LENB", "AGB"]
FORM_HEAD = """/* Generated by palace/tools/build_page.py from the formations of the One Hundred Moves
   page (course/moves/index.html), with the fact fixes in tools/formation_fixes.json applied.
   Do not edit: change the Moves page or the fixes, then run build_page.py.
   Each formation F.name(mode) returns {prep?(s), p(i,s,o), draw?(s,a)}: p sets x, y
   (unit square, y up), colour index c, radius r and alpha a of point i at progress s;
   draw paints lines and text through `ctx`. The palace passes a recording ctx
   (see palace.js) so the same calls become 3-D line segments and labels. */
(()=>{
'use strict';
"""


def formations():
    html = MOVES.read_text()
    a = html.index("<script>\n(()=>{\n'use strict';\n") + len("<script>\n(()=>{\n'use strict';\n")
    b = html.index("/* ---------- the moves ---------- */", a)
    body = html[a:b]
    for fx in json.loads(FIXES.read_text()):
        n = body.count(fx["old"])
        if n != 1:
            sys.exit(f"formation fix matches {n} times, not once: {fx['why']}")
        body = body.replace(fx["old"], fx["new"])
    specs = []
    for name in SPECS:
        if re.search(rf"^const {name}=", body, re.M):
            continue
        m = re.search(rf"^const {name}=.*?;$", html, re.M)
        if not m:
            sys.exit(f"spec {name} not found on the Moves page")
        specs.append(m.group(0))
    exp = ("\n".join(specs) + "\n\nwindow.MovesF={F,N,H,G,clamp,lerp,ease,sstep,sig,softmax,along,V,FG,BL,GD,FT,SPECS:{"
           + ",".join(SPECS) + "},\n  setCtx(c){ctx=c;},setRGB(rgb,muted){RGB=rgb;MUTED=muted;}};\n})();\n")
    return FORM_HEAD + body + exp


def build():
    palace = json.loads((ROOT / "source" / "palace.json").read_text())
    allm = moves_text()
    used = {mv for r in palace["rooms"] for o in r["objects"] + r["also"] for mv in o["moves"]}
    used |= set(palace["prologue"]["moves"]) | set(palace["epilogue"]["moves"])
    missing = sorted(used - set(allm))
    if missing:
        sys.exit(f"moves not found on the Moves page: {missing}")
    data = {"palace": palace, "moves": {k: allm[k] for k in sorted(used, key=lambda x: (x[0], int(x[1:])))}}
    text = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    text = text.replace("</", "<\\/")
    return f'{BEGIN}\n<script type="application/json" id="palace-data">{text}</script>\n{END}'


def main():
    check = "--check" in sys.argv[1:]
    form = formations()
    if check and (not FORM.exists() or FORM.read_text() != form):
        print(f"{FORM.name} has drifted from the Moves page and tools/formation_fixes.json: run tools/build_page.py")
        sys.exit(1)
    if not check:
        FORM.write_text(form)
    page = PAGE.read_text()
    pat = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if not pat.search(page):
        sys.exit(f"markers not found in {PAGE}")
    new = pat.sub(lambda _: build(), page)
    if check:
        if new != page:
            print(f"{PAGE.name} is stale: run tools/build_page.py")
            sys.exit(1)
        print("palace page is current")
        return
    PAGE.write_text(new)
    print(f"wrote data block into {PAGE}")


if __name__ == "__main__":
    main()
